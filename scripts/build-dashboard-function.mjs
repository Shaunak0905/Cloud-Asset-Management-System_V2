// Builds supabase/setup/send-reminders-dashboard.ts: the send-reminders Edge
// Function as ONE file, for pasting into the Supabase dashboard editor.
// The repo keeps the function in two files (index.ts + reminders.ts) so the
// logic can be tested; this joins them. Run: npm run reminders:dashboard
// (tests/reminders.test.ts fails if the built file is out of date).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "supabase/functions/send-reminders");
export const OUTPUT = path.join(
  ROOT,
  "supabase/setup/send-reminders-dashboard.ts",
);

const HEADER = `// send-reminders — single-file version for the Supabase dashboard editor.
// Paste this whole file as the function's index.ts, then deploy.
// GENERATED by \`npm run reminders:dashboard\` from
// supabase/functions/send-reminders/ (reminders.ts + index.ts) — do not edit.

`;

export function buildDashboardFunction() {
  const reminders = readFileSync(path.join(SOURCE, "reminders.ts"), "utf8");
  const entry = readFileSync(path.join(SOURCE, "index.ts"), "utf8")
    .split("\n")
    // The import is not needed once both parts are in one file.
    .filter((line) => !line.startsWith("import "))
    .join("\n");
  return `${HEADER}${reminders}\n// --- Entry point (from index.ts) ---\n${entry}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, buildDashboardFunction());
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}`);
}
